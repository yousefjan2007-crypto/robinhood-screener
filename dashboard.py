def write_page(page: str, out: str) -> None:
    """tmp + os.replace so Pages never serves a half-written file."""
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    tmp = f"{out}.{os.getpid()}.tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(page)
    os.replace(tmp, out)


def main() -> str:
    """Render the committed data to config.DOCS_DIR/index.html and return the path."""
    scan, led, paper, live, run_log = load_inputs()
    out = os.path.join(config.DOCS_DIR, "index.html")
    write_page(render(scan, led, paper, live, run_log), out)
