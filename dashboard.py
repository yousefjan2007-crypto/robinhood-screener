    scan = scan if isinstance(scan, dict) else {}
    survivors = [s for s in (scan.get("survivors") or []) if isinstance(s, dict)]
    champ = scan.get("champion") if isinstance(scan.get("champion"), dict) else {}
    band = str(scan.get("band") or champ.get("entry_band") or config.DEFAULT_ENTRY_BAND)
    exit_name = str(champ.get("exit") or config.IMPROVE_DEFAULT_EXIT_CHAMPION)
    scan_ts = _num(scan.get("scan_ts"), 0.0)
